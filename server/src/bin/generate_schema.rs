// server/src/bin/generate_schema.rs
use schemars::schema::RootSchema;
use std::fs;
use std::path::Path;
use typify::{TypeSpace, TypeSpaceSettings};

fn main() {
    let yaml_path = "../doc/openapi.yaml";
    println!("Reading OpenAPI spec from: {}", yaml_path);

    let content = fs::read_to_string(yaml_path)
        .unwrap_or_else(|e| panic!("Failed to read {}: {}", yaml_path, e));

    let openapi_val: serde_json::Value = serde_yaml::from_str(&content)
        .unwrap_or_else(|e| panic!("Failed to parse YAML: {}", e));

    let schemas = openapi_val
        .get("components")
        .and_then(|c| c.get("schemas"))
        .cloned()
        .unwrap_or(serde_json::json!({}));

    // typify が $ref を解決できるように JSON Schema の root definitions に載せ替える
    let mut schema_str = schemas.to_string();
    schema_str = schema_str.replace("#/components/schemas/", "#/definitions/");

    let root_json = serde_json::json!({
        "$schema": "http://json-schema.org/draft-07/schema#",
        "definitions": serde_json::from_str::<serde_json::Value>(&schema_str).unwrap()
    });

    let root_schema: RootSchema = serde_json::from_value(root_json)
        .unwrap_or_else(|e| panic!("Failed to construct RootSchema: {}", e));

    let mut type_space = TypeSpace::new(
        TypeSpaceSettings::default()
            .with_derive("Clone".to_string())
            .with_derive("Debug".to_string()),
    );

    type_space
        .add_root_schema(root_schema)
        .unwrap_or_else(|e| panic!("typify failed to process schemas: {}", e));

    // 出力先ディレクトリの作成
    let out_dir = Path::new("src/generated");
    if !out_dir.exists() {
        fs::create_dir_all(out_dir).expect("Failed to create src/generated dir");
    }

    let raw_tokens = type_space.to_stream();
    let syntax_tree = syn::parse2(raw_tokens).expect("Failed to parse generated Rust tokens");
    let formatted_code = prettyplease::unparse(&syntax_tree);

    let output_file_content = format!(
        "{}\n{}",
        "// Generated by typify. DO NOT EDIT.\n#![allow(clippy::all, unused_imports, dead_code)]\nuse serde::{Deserialize, Serialize};",
        formatted_code
    );

    let api_schema_path = out_dir.join("api_schema.rs");
    fs::write(&api_schema_path, output_file_content)
        .expect("Failed to write src/generated/api_schema.rs");

    println!(" Successfully generated: {:?}", api_schema_path);
}